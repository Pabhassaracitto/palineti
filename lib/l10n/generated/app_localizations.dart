class _AppLocalizationsDelegate
    extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) =>
      AppLocalizations._localizedValues.containsKey(_localeNameOf(locale)) ||
      AppLocalizations._localizedValues.containsKey(locale.languageCode);

  @override
  Future<AppLocalizations> load(Locale locale) {
    final localeName = _lookupLocaleName(locale);
    return SynchronousFuture<AppLocalizations>(AppLocalizations(localeName));
  }

  @override
  bool shouldReload(_AppLocalizationsDelegate old) => false;

  static String _lookupLocaleName(Locale locale) {
    final localeName = _localeNameOf(locale);
    if (AppLocalizations._localizedValues.containsKey(localeName)) {
      return localeName;
    }
    if (AppLocalizations._localizedValues.containsKey(locale.languageCode)) {
      return locale.languageCode;
    }
    return 'en';
  }

  static String _localeNameOf(Locale locale) {
    final countryCode = locale.countryCode;
    if (countryCode == null || countryCode.isEmpty) {
      return locale.languageCode;
    }
    return '${locale.languageCode}_${countryCode}';
  }
}
